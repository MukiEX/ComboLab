// Extract the notation parser from ComboLab.html and test it.
const fs = require("fs");
const html = fs.readFileSync(__dirname + "/../reframework/data/ComboLab/ComboLab.html", "utf8");
const code = html.split("/* ===================== notation parser (shared with tests) ===================== */")[1].split("/* =================== end parser =================== */")[0];
const P = new Function(code + "; return {parseCombo, splitNotation, hashSteps, triggerText, CB, MB};")();
let fail = 0;
const eq = (a, b, m) => { const A = JSON.stringify(a), B = JSON.stringify(b); if (A !== B) { fail++; console.log("FAIL", m, "\n  got ", A, "\n  want", B); } };
const s = P.parseCombo("2LP > 2LP, 5LK > DR > 5LP, 5HP > DR > 5HK, 5MP~4HP > [2]8HK", "classic");
eq(s.map(x => x.label), ["2LP","2LP","5LK","DR","5LP","5HP","DR","5HK","5MP","4HP","[2]8HK"], "labels");
eq(s.map(x => x.sep), ["start",">",",",">",">",",",">",">",",","~",">"], "seps");
eq(s.map(x => x.kind), ["hit","hit","hit","move","hit","hit","move","hit","hit","hit","hit"], "kinds");
eq(s[3].trigger, {type:"button",mask:288,mode:"all"}, "DR cancel trigger");
const raw = P.parseCombo("DR > 5MP, 5HP", "classic");
eq(raw[0].trigger, {type:"rawdr",mask:288,mode:"all"}, "DR at the start is a raw Drive Rush (parry, 66)");
eq(P.parseCombo("2LP, DR > 5LP", "classic")[1].trigger.type, "rawdr", "DR after a link is raw too");
eq(P.parseCombo("DR > 5MP", "modern")[0].trigger.mask, P.MB.DP, "modern raw DR uses the parry button");
eq(P.triggerText(raw[0].trigger, "classic"), "parry, 66", "raw DR text");
eq(s[10].trigger, {type:"button",mask:512,mode:"all"}, "charge HK");
const t = P.parseCombo("cr.MK xx 236P, j.HP 5HP -> SA2, 66, 9, MP+MK, PPP, DI", "classic");
eq(t.map(x => x.label), ["2MK","236P","j.HP","5HP","SA2","66","9","MPMK","PPP","DI"], "alt labels");
eq(t.map(x => x.sep), ["start",">",",",",",">",",",",",",",",",","], "alt seps");
eq(t[1].trigger, {type:"button",mask:112,mode:"any"}, "P any");
eq(t[7].trigger, {type:"button",mask:288,mode:"all"}, "MP+MK chord");
eq(t.filter(x => x.error).length, 0, "no errors");
const m = P.parseCombo("2L > 236SP, 5M > DR > 5H", "modern");
eq(m.map(x => x.error), [null,null,null,null,null], "modern ok");
eq(m[1].trigger.mask, 0x20, "modern SP");
eq(P.parseCombo("5XP", "classic")[0].error !== null, true, "bad button flagged");
const ov = P.parseCombo("5XP", "classic", {0: {trigger: {type:"button",mask:64,mode:"all"}}});
eq(ov[0].error, null, "override clears error");
const air = P.parseCombo("5LK~5LK~5LK > j.214P, 5HP > 236[PP], 8, j.HP", "classic");
eq(air.map(x => x.label), ["5LK","5LK","5LK","j.214P","5HP","236[PP]","8","j.HP"], "air special, held, jump");
eq(air[5].trigger, {type:"button",mask:112,mode:"any"}, "held PP");
eq(air.filter(x => x.error).length, 0, "no errors in air/held");
console.log(fail ? fail + " failed" : "parser OK");
process.exit(fail ? 1 : 0);
